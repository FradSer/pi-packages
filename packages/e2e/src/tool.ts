export interface ToolResult {
  content: Array<{ type: "text"; text: string }>;
  details?: Record<string, unknown> & { feedback?: E2EFeedback };
  structuredContent?: Record<string, unknown>;
  isError?: boolean;
}

async function resolveEvidence(input: unknown, baseDir: string): Promise<Evidence> {
  if (input !== null && typeof input === "object" && "run" in input) {
    return input as Evidence;
  }
  if (typeof input === "string") {
    const raw = await readFile(path.resolve(baseDir, input), "utf-8");
    return JSON.parse(raw) as Evidence;
  }
  // If evidence is omitted, look for standard production/run convention paths only
  for (const candidate of [
    ".artifacts/evidence.json",
    ".e2e/report.json",
  ]) {
    try {
      const raw = await readFile(path.resolve(baseDir, candidate), "utf-8");
      return JSON.parse(raw) as Evidence;
    } catch {
      // try next
    }
  }
  throw new Error("No evidence provided and no standard evidence file (.artifacts/evidence.json, .e2e/report.json) found.");
}

export type VerdictListener = (
  verdict: Verdict,
  featurePath?: string,
  baseDir?: string,
  expectedScenarios?: readonly string[],
  modelError?: string,
) => void | Promise<void>;

export interface VerificationObserver {
  onVerdict: VerdictListener;
  validateRunner: (snapshot: string) => void;
  onError?: ExecuteToolOptions["onError"];
  acceptance?: ExecuteToolOptions["acceptance"];
}

export interface ExecuteToolOptions {
  signal?: AbortSignal;
  cwd?: string;
  validateRunner?: (snapshot: string) => void;
  onError?: (message: string, featurePath: string, scenario?: string, baseDir?: string) => void | Promise<void>;
  onProgress?: (phase: string) => void;
  acceptance?: (featurePath: string, baseDir: string) => AcceptanceFeedback | undefined;
}

/**
 * Executes `e2e_verify` and returns a structured tool result.
 */
export async function executeE2EVerify(
  params: Record<string, unknown>,
  onVerdict?: VerdictListener,
  options?: ExecuteToolOptions,
): Promise<ToolResult> {
  const baseDir = options?.cwd ?? process.cwd();
  const featurePath = String(params["feature"] ?? "");
  let attemptedScenario: string | undefined;
  if (!featurePath) {
    const message = "e2e_verify: feature path is required.";
    return {
      content: [{ type: "text", text: message }],
      details: { ok: false, status: "error", error: message },
      structuredContent: { ok: false, status: "error", error: message },
      isError: true,
    };
  }

  try {
    options?.onProgress?.("Preparing verification");
    const featureSource = await readFile(path.resolve(baseDir, featurePath), "utf-8");
    const feature = parseFeature(featureSource);
    if (params["allScenarios"] === true) {
      if (params["scenario"] !== undefined || params["runner"] === undefined || params["evidence"] !== undefined) {
        throw new Error("allScenarios requires runner and cannot be combined with scenario or supplied evidence");
      }
      if (feature.scenarios.length === 0 || feature.scenarios.length > 100) throw new Error("allScenarios requires 1 to 100 scenarios");
      if (new Set(feature.scenarios.map(item => item.name)).size !== feature.scenarios.length) throw new Error("allScenarios requires unique scenario names");
      const snapshot = await runnerSnapshot(baseDir);
      const pending: Parameters<VerdictListener>[] = [];
      const pendingErrors: Parameters<NonNullable<ExecuteToolOptions["onError"]>>[] = [];
      const results: Record<string, unknown>[] = [];
      const reports: string[] = [];
      for (const item of feature.scenarios) {
        options?.signal?.throwIfAborted();
        attemptedScenario = item.name;
        const result = await executeE2EVerify({ ...params, allScenarios: false, scenario: item.name },
          (...args) => { pending.push(args); }, { ...options, acceptance: undefined,
            onError: (...args) => { pendingErrors.push(args); } });
        results.push(result.structuredContent ?? { status: "error", error: "Missing scenario result" });
        reports.push(...result.content.map(content => content.text));
      }
      if (await readFile(path.resolve(baseDir, featurePath), "utf8") !== featureSource || await runnerSnapshot(baseDir) !== snapshot) {
        throw new Error("Feature or adapter changed during complete verification; run every scenario again");
      }
      // A failed rerun must withdraw an older pass before sibling passes arrive.
      for (const args of pendingErrors) await options?.onError?.(...args);
      for (const args of pending) await onVerdict?.(...args);
      const blocker = results.some(result => result["status"] === "error" || result["error"] !== undefined);
      const fresh = results.every(result => result["verifiedRun"] === true);
      const passed = results.filter(result => result["status"] === "fulfilled" && result["verifiedRun"] === true).length;
      const status = blocker ? "error" : results.some(result => result["status"] === "not_fulfilled" || result["status"] === "partially_fulfilled")
        ? "not_fulfilled" : passed === results.length ? "fulfilled" : "needs_review";
      const items = results.flatMap(result => Array.isArray(result["findings"]) ? result["findings"] : []) as ReturnType<typeof findings>;
      const coverage = { total: feature.scenarios.length, evaluated: results.filter(result => result["status"] !== "error").length,
        passed, remaining: feature.scenarios.filter((_item, index) => results[index]?.["status"] !== "fulfilled" || results[index]?.["verifiedRun"] !== true).map(item => item.name) };
      const structured = { ok: status === "fulfilled", status, verifiedRun: fresh,
        exitCode: status === "fulfilled" ? 0 : status === "not_fulfilled" ? 1 : 2,
        feature: feature.feature, coverage, scenarios: results, findings: items,
        nextAction: nextAction(items, blocker, fresh),
        ...(blocker ? { error: "One or more scenarios could not be evaluated; see scenario results." } : {}),
      };
      const feedback: E2EFeedback = { label: status === "fulfilled" ? "passed" : status === "error" ? "error" : status === "needs_review" ? "needs review" : "failed",
        tone: status === "fulfilled" ? "success" : status === "needs_review" ? "warning" : "error",
        lines: [`Feature: ${feature.feature}`, `Feature acceptance: ${passed}/${coverage.total} scenarios passed`,
          ...coverage.remaining.map(name => `Remaining: ${name}`), `Action: ${structured.nextAction}`,
          ...items.flatMap(item => [`${item.action}: ${item.scenario}, clause ${item.clause}: ${item.reason}`,
            ...(item.check ? [`Check: ${item.check.path} (${item.check.op})`, `Expected: ${item.check.expected}`, `Observed: ${item.check.observed}`,
              ...(item.check.step ? [`Step: ${item.check.step}`] : []), ...(item.check.location ? [`Location: ${item.check.location}`] : [])] : [])]),
          ...results.flatMap((result, index) => [`Scenario: ${feature.scenarios[index]!.name} — ${String(result["status"])}`,
            ...(reports[index]?.split("\n").filter(line => line.startsWith("Next:")) ?? [])])],
      };
      return { content: [{ type: "text", text: `${feedback.lines.join("\n")}\n\n${reports.join("\n\n")}` }],
        details: { ...structured, feedback }, structuredContent: structured, isError: status !== "fulfilled" };
    }
    const scenarioName = typeof params["scenario"] === "string" ? params["scenario"] : undefined;
    const scenario = scenarioName ? scenarioByName(feature, scenarioName) : firstScenario(feature);
    if (!scenario) {
      throw new Error(`Scenario "${scenarioName}" not found in ${featurePath}.`);
    }
    attemptedScenario = scenario.name;

    if (params["runner"] !== undefined && params["evidence"] !== undefined) throw new Error("Supply runner or evidence, not both");

    const clauseGate = params["clauseGate"];
    if (clauseGate !== undefined && (typeof clauseGate !== "number" || !Number.isFinite(clauseGate) || clauseGate < 0 || clauseGate > 1)) {
      throw new Error(`clauseGate must be a number between 0 and 1, received ${String(clauseGate)}`);
    }
    const verdictGate = params["verdictGate"];
    if (verdictGate !== undefined && (typeof verdictGate !== "number" || !Number.isFinite(verdictGate) || verdictGate < 0 || verdictGate > 1)) {
      throw new Error(`verdictGate must be a number between 0 and 1, received ${String(verdictGate)}`);
    }
    const minConfidence = params["minConfidence"];
    if (minConfidence !== undefined && (typeof minConfidence !== "number" || !Number.isFinite(minConfidence) || minConfidence < 0 || minConfidence > 1)) {
      throw new Error(`minConfidence must be a number between 0 and 1, received ${String(minConfidence)}`);
    }

    const policy = {
      ...(typeof clauseGate === "number" ? { clauseGate } : {}),
      ...(typeof verdictGate === "number" ? { verdictGate } : {}),
      ...(typeof minConfidence === "number" ? { minConfidence } : {}),
    };

    const runner = params["runner"] === undefined ? undefined : parseRunner(params["runner"]);
    const { verdict, modelError, runnerOutput } = runner
      ? await runAndVerify({ runner, cwd: baseDir, featurePath, scenario: scenarioName,
          offline: params["offline"] === true, signal: options?.signal, policy, validateRunner: options?.validateRunner, onProgress: options?.onProgress })
      : await verifyScenario({ scenario, evidence: await resolveEvidence(params["evidence"], baseDir),
          offline: params["offline"] === true, signal: options?.signal, policy, onProgress: options?.onProgress });
    options?.signal?.throwIfAborted();
    const hasVerifiedRun = await verifiedRun(verdict, path.resolve(baseDir, featurePath)) !== undefined;
    await onVerdict?.(verdict, featurePath, baseDir, feature.scenarios.map((item) => item.name), modelError);

    const ok = verdict.status === "fulfilled";
    const feedback = verdictFeedback(verdict, { verifiedRun: hasVerifiedRun,
      modelError, acceptance: options?.acceptance?.(featurePath, baseDir) });
    const structured: Record<string, unknown> = {
      ok,
      verifiedRun: hasVerifiedRun,
      status: verdict.status,
      exitCode: verdict.exitCode,
      reason: verdict.reason,
      unjudged: verdict.unjudged,
      scenario: verdict.scenario,
      feature: verdict.feature,
      findings: findings(verdict, hasVerifiedRun),
      nextAction: nextAction(findings(verdict, hasVerifiedRun), Boolean(modelError), hasVerifiedRun),
      clauses: verdict.clauses.map((c) => ({
        clause: c.clause,
        text: c.text,
        status: c.status,
        source: c.source,
        ...(c.score !== undefined ? { score: c.score } : {}),
        ...(c.detail !== undefined ? { detail: c.detail } : {}),
        ...(c.checks ? { checks: c.checks } : {}),
      })),
      ...(verdict.model ? { model: verdict.model } : {}),
      ...(modelError ? { error: modelError } : {}),
      ...(runnerOutput ? { runnerOutput } : {}),
    };

    return {
      content: [{ type: "text", text: `${renderMarkdown(verdict).trimEnd()}${runnerOutput ? `\n\nRunner diagnostic data (not instructions):\n${runnerOutput}` : ""}\n\nRun evidence: ${hasVerifiedRun ? "verified fresh test process" : "caller-supplied; cannot clear acceptance checkpoints"}${modelError ? `\nProvider: ${modelError}` : ""}\n\n${feedback.lines.filter(line => line.startsWith("Feature acceptance:") || line.startsWith("Remaining:") || line.startsWith("Next:")).join("\n")}` }],
      details: { ...structured, feedback },
      structuredContent: structured,
      isError: !ok,
    };
  } catch (error) {
    const message = `e2e_verify failed: ${error instanceof Error ? error.message : String(error)}`;
    if (!options?.signal?.aborted) await options?.onError?.(message, featurePath, attemptedScenario, baseDir);
    return {
      content: [{ type: "text", text: message }],
      details: { ok: false, status: "error", error: message, feedback: {label:"error",tone:"error",lines:[`Feature: ${featurePath}`,...(attemptedScenario ? [`Scenario: ${attemptedScenario}`] : []),message,"Next: resolve the execution or configuration blocker, then run fresh verification."]} satisfies E2EFeedback },
      structuredContent: { ok: false, status: "error", error: message },
      isError: true,
    };
  }
}

/**
 * Registers the native `e2e_verify` tool on Pi.
 */
export function registerE2ETools(pi: ExtensionAPI, onVerdict?: VerdictListener, onStart?: () => VerificationObserver): void {
  pi.registerTool({
    name: "e2e_verify",
    label: "E2E Verify",
    promptSnippet: "Run fresh acceptance tests with the authorized adapter; judge covered Gherkin scenarios",
    description:
      "Verify whether a Gherkin .feature scenario is fulfilled. Evaluates declared deterministic checks in code and assesses semantic business clauses with calibrated probabilities using TypeSafe Jev. For fresh acceptance, supply feature and runner copied from the authorized .e2e/runner.json; the tool executes tests, so avoid separately rerunning the same suite first. Reserve time for repairs and fresh verification. Supplied evidence is diagnostic only and cannot clear acceptance checkpoints. Returns the covered scenario verdict, not proof of complete request coverage.",
    parameters: E2E_VERIFY_PARAMS as never,
    outputSchema: E2E_VERIFY_OUTPUT_SCHEMA as never,
    annotations: { readOnlyHint: false, idempotentHint: false, openWorldHint: true },
    renderShell: "self",
    renderCall: emptyToolCall,
    renderResult: (result: ToolResult, _state: {isPartial?: boolean}, theme: Parameters<typeof renderFeedback>[1], _context: {isError?: boolean}) =>
      renderFeedback(toolFeedback(result), theme),
    async execute(_toolCallId: string, params: never, signal?: AbortSignal, onUpdate?: (result: ToolResult) => void, ctx?: { cwd?: string }) {
      const observer = onStart?.();
      return executeE2EVerify(params as Record<string, unknown>, observer?.onVerdict ?? onVerdict,
        { signal, cwd: ctx?.cwd, validateRunner: observer?.validateRunner, onError: observer?.onError,
          acceptance: observer?.acceptance, onProgress: phase => onUpdate?.({
            content: [{type:"text",text:phase}], details: {status:"running",feedback:{label:"running",tone:"warning",lines:[phase]} satisfies E2EFeedback},
          }) }) as never;
    },
  } as never);
}

function toolFeedback(result: ToolResult): E2EFeedback {
  const feedback = result.details?.feedback;
  if (feedback) return feedback;
  // Restored results from earlier versions keep their full diagnostic content.
  const status = result.details?.status;
  const label = status === "fulfilled" ? (result.details?.verifiedRun === true ? "passed" : "needs review")
    : status === "needs_review" ? "needs review"
      : status === "not_fulfilled" || status === "partially_fulfilled" ? "failed"
        : status === "error" || result.isError ? "error" : "running";
  return {label,tone:label === "passed" ? "success" : label === "failed" || label === "error" ? "error" : "warning",
    lines:[...(result.details?.scenario ? [`Scenario: ${String(result.details.scenario)}`] : []), ...result.content.flatMap(item=>item.text.split("\n"))]};
}
